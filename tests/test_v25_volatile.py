"""(v2.5) Run-varying import-time values: a value that differs between two imports of the same code (a random token,
a thread id, the time of import, a registry keyed by id(), a version read from git) is compared by the parts that do
not vary. Unchanged code must report nothing; a real change to such a value must still be reported."""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "src"))

from dc_engine import importstate as S  # noqa: E402

CORE = '''import subprocess, os, threading, time, uuid


class Lock:
    def __init__(self, name):
        self.name = name
        self.token = str(uuid.uuid4())


class A: pass
class B: pass
class C: pass


def on_a(): pass
def on_b(): pass


LOCK = Lock("hdf5")
REGISTRY = {id(A): on_a, id(B): on_b}
MARKS = frozenset([id(A), id(B)])
STARTED = time.time()
MINUTE = time.strftime("%Y-%m-%d %H:%M", time.localtime())
TIMER = time.time
MAIN = threading.current_thread()
try:
    COMMIT = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True,
                            cwd=os.path.dirname(__file__)).stdout.strip()
except OSError:
    COMMIT = ""
BANNER = f"Generated by pkg 1.0{'+' + COMMIT if COMMIT else ''}. All rights reserved."
CHECK = lambda x: x in {"alpha", "beta", "gamma", "delta", "epsilon"}
PLAIN = {"a": 1}
'''


def _git(cwd, *a):
    subprocess.run(["git", "-c", "user.email=t@t", "-c", "user.name=t", *a], cwd=cwd, check=True, capture_output=True)


class Volatile(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.root = tempfile.mkdtemp()
        os.makedirs(os.path.join(cls.root, "pkg"))
        open(os.path.join(cls.root, "pkg", "__init__.py"), "w").write("")
        open(os.path.join(cls.root, "pkg", "core.py"), "w").write(CORE)
        _git(cls.root, "init", "-q")
        _git(cls.root, "add", "-A")
        _git(cls.root, "commit", "-qm", "base")
        cls.files = ["pkg/__init__.py", "pkg/core.py"]
        cls.base = S.base_snapshot(cls.root, cls.files, sys.executable, os.path.join(cls.root, "base.json"))
        os.environ["PROVISO_OFF"] = "volatile"
        try:
            cls.base_off = S.base_snapshot(cls.root, cls.files, sys.executable, os.path.join(cls.root, "base_off.json"))
        finally:
            del os.environ["PROVISO_OFF"]

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.root, True)

    def edit(self, old=None, new=None):
        p = os.path.join(self.root, "pkg", "core.py")
        src = CORE if old is None else CORE.replace(old, new)
        self.assertTrue(old is None or old in CORE)
        open(p, "w").write("# edited\n" + src)
        self.addCleanup(lambda: open(p, "w").write(CORE))

    def diff(self, pad=7919):
        cur = S.snapshot(self.root, self.files, sys.executable, heap_pad=pad,
                         tree_keys=sorted(self.base.get("patterns") or {}))
        return S.diff(self.base, cur)

    def test_base_found_the_varying_values(self):
        pats = set(self.base["patterns"])
        for k in ("pkg.core:LOCK", "pkg.core:STARTED", "pkg.core:MAIN", "pkg.core:BANNER", "pkg.core:COMMIT",
                  "pkg.core:MINUTE"):
            self.assertIn(k, pats)
        self.assertNotIn("pkg.core:PLAIN", pats)
        # a reference to a clock function is not itself run-varying (the moved clock of some samples must not show)
        self.assertNotIn("pkg.core:TIMER", self.base["unstable"])

    def test_value_coarser_than_the_sampling_time_keeps_its_format(self):
        self.edit('MINUTE = time.strftime("%Y-%m-%d %H:%M", time.localtime())',
                  'MINUTE = time.strftime("%d/%m/%Y %H:%M", time.localtime())')
        self.assertIn("pkg.core:MINUTE", self.diff()["changed"])

    def test_unchanged_code_reports_nothing(self):
        self.edit()
        for pad in (0, 5003, 30011):
            d = self.diff(pad)
            self.assertEqual(d["changed"], [], pad)
        self.assertIn("pkg.core:LOCK", d["covered"])

    def test_without_the_mechanism_the_same_values_are_reported(self):
        self.edit()
        cur = S.snapshot(self.root, self.files, sys.executable)
        os.environ["PROVISO_OFF"] = "volatile"
        try:
            changed = set(S.diff(self.base_off, cur)["changed"])
        finally:
            del os.environ["PROVISO_OFF"]
        self.assertLessEqual({"pkg.core:LOCK", "pkg.core:STARTED", "pkg.core:REGISTRY"}, changed)

    def test_stable_part_of_a_varying_object_still_counts(self):
        self.edit('LOCK = Lock("hdf5")', 'LOCK = Lock("netcdf")')
        self.assertIn("pkg.core:LOCK", self.diff()["changed"])

    def test_other_shape_of_the_varying_part_counts(self):
        self.edit("self.token = str(uuid.uuid4())", "self.token = uuid.uuid4().hex")
        self.assertIn("pkg.core:LOCK", self.diff()["changed"])

    def test_registry_keyed_by_id_is_compared_by_what_it_points_to(self):
        self.edit("REGISTRY = {id(A): on_a, id(B): on_b}", "REGISTRY = {id(A): on_a, id(C): on_b}")
        self.assertIn("pkg.core:REGISTRY", self.diff()["changed"])

    def test_registry_value_change_counts(self):
        self.edit("REGISTRY = {id(A): on_a, id(B): on_b}", "REGISTRY = {id(A): on_b, id(B): on_a}")
        self.assertIn("pkg.core:REGISTRY", self.diff()["changed"])

    def test_id_set_member_change_counts(self):
        self.edit("MARKS = frozenset([id(A), id(B)])", "MARKS = frozenset([id(A), id(C)])")
        self.assertIn("pkg.core:MARKS", self.diff()["changed"])

    def test_text_around_a_git_version_still_counts(self):
        self.edit("All rights reserved.", "Some rights reserved.")
        self.assertIn("pkg.core:BANNER", self.diff()["changed"])

    def test_thread_object_replaced_counts(self):
        self.edit("MAIN = threading.current_thread()", 'MAIN = threading.Thread(name="MainThread")')
        self.assertIn("pkg.core:MAIN", self.diff()["changed"])

    def test_plain_value_change_counts(self):
        self.edit('PLAIN = {"a": 1}', 'PLAIN = {"a": 2}')
        self.assertEqual(self.diff()["changed"], ["pkg.core:PLAIN"])

    def test_set_constant_in_code_is_stable(self):
        self.assertNotIn("pkg.core:CHECK", self.base["unstable"])


class Generalise(unittest.TestCase):
    def test_leaf_keeps_common_start_end_and_length(self):
        p = S.generalise(["s", "str", "v1.0+abc12."], ["s", "str", "v1.0+9f3e0."])
        self.assertEqual(p, ["w", "str", "v1.0+", ".", 11])
        self.assertTrue(S.covers(p, ["s", "str", "v1.0+zzzzz."]))
        self.assertFalse(S.covers(p, ["s", "str", "v2.0+zzzzz."]))
        self.assertFalse(S.covers(p, ["s", "str", "v1.0+zz."]))

    def test_other_kind_of_leaf_is_not_covered(self):
        p = S.generalise(["s", "int", "5"], ["s", "int", "9"])
        self.assertTrue(S.covers(p, ["s", "int", "123"]))
        self.assertFalse(S.covers(p, ["s", "str", "123"]))
        self.assertFalse(S.covers(p, ["s", "NoneType", "None"]))

    def test_dict_with_varying_keys(self):
        t = lambda a, b: ["m", "dict", [[["s", "str", a], ["s", "str", "x"]], [["s", "str", b], ["s", "str", "y"]],
                                        [["s", "str", "fixed"], ["s", "int", "1"]]]]
        p = S.generalise(t("k1-aaaa", "k2-bbbb"), t("k1-cccc", "k2-dddd"))
        self.assertTrue(S.covers(p, t("k1-eeee", "k2-ffff")))
        bad = t("k1-eeee", "k2-ffff")
        bad[2][2][1] = ["s", "int", "2"]
        self.assertFalse(S.covers(p, bad))
        more = t("k1-eeee", "k2-ffff")
        more[2].append([["s", "str", "new"], ["s", "int", "1"]])
        self.assertFalse(S.covers(p, more))

    def test_reordered_list_becomes_order_free_only_there(self):
        a = ["l", "tuple", [["s", "str", "x"], ["s", "str", "y"], ["s", "str", "z"]]]
        b = ["l", "tuple", [["s", "str", "z"], ["s", "str", "x"], ["s", "str", "y"]]]
        p = S.generalise(a, b)
        self.assertTrue(S.covers(p, ["l", "tuple", [["s", "str", "y"], ["s", "str", "z"], ["s", "str", "x"]]]))
        self.assertFalse(S.covers(p, ["l", "tuple", [["s", "str", "y"], ["s", "str", "z"], ["s", "str", "w"]]]))


if __name__ == "__main__":
    unittest.main()
