"""How concentrated test time is in B1's projects, and whether the tools select the slowest tests.

  python research/v2/b1_time_concentration.py summary PROJECT [PROJECT ...]
      results/b1/time_concentration.md: per project, the 10 slowest tests' share of the suite's test time.
  python research/v2/b1_time_concentration.py detail PROJECT [--top 15] [--max-load L]
      results/b1/PROJECT/time_concentration.md: the slowest tests, their share of test time, and in how many pairs
      ValueRTS (proviso), testmon and NameRTS selected each, in scenarios S and F.

Test time: each test's own duration in the plain run at P (base_outcomes.json, which every B1 pair saved), summed over
the project's ok pairs; a test's share = its summed time / the summed time of all tests (setup/teardown included as
the outcomes plugin records them; not wall time, which includes collection and worker start). Ranked by summed time.

detail recomputes each tool's selection from the pair's saved data (Proviso's map, testmon database, NameRTS cache;
copies, so the saved data is not changed), with b1.selections() on a tree put in the scenario's state, exactly as
b1.py selected (in F, tests of test files the commit edits count as selected, as in b1.score). No test is run. The
recomputed selection sizes are compared with the sizes in the rows (reported). Per-pair results are kept in
$PROVISO_WORK/PROJECT/time_concentration/ (resumable). Before each pair it waits while the 1-minute load is above
--max-load (default 9), so it only uses spare capacity."""
from __future__ import annotations

import glob
import json
import os
import shutil
import statistics
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import b1  # noqa: E402
import pipeline as PL  # noqa: E402
from dc_engine import impact as I  # noqa: E402

TOOLS = [("proviso", "ValueRTS"), ("testmon", "testmon"), ("namerts", "NameRTS")]
# testmon keys its data by the installed packages: httpx/httpcore were added to the shared venv on 2026-11-28 (for
# datasette's re-run), after these pairs were recorded, so testmon would treat every test as affected. Its own setting
# testmon_ignore_dependencies leaves them out (pytest-testmon is the default ignore, kept); checked against the rows.
TESTMON_IGNORE = ["pytest-testmon", "httpx", "httpcore"]


def _testmon_select_same_env(orig):
    def select(tree, db):
        keep = list(PL.CFG["pytest_args"])
        PL.CFG["pytest_args"] = keep + ["-o", "testmon_ignore_dependencies=" + " ".join(TESTMON_IGNORE)]
        try:
            return orig(tree, db)
        finally:
            PL.CFG["pytest_args"] = keep
    return select


PL.testmon_select = _testmon_select_same_env(PL.testmon_select)


def ok_rows(name):
    return sorted((r for r in b1.rows(name).values() if r.get("status") == "ok"), key=lambda r: r.get("rank", 0))


def durations(name):
    """{test: [seconds at P per pair]}, total test seconds over pairs, number of pairs with outcomes."""
    per, total, n = {}, 0.0, 0
    for r in ok_rows(name):
        base = PL.jload(os.path.join(PL.BASE_WORK, name, "b1", r["id"][:12], "base_outcomes.json"))
        if not base:
            continue
        n += 1
        for t, (_, s) in base.items():
            if "::" in t and s:
                per.setdefault(t, []).append(s)
                total += s
    return per, total, n


def ranked(per):
    return sorted(per, key=lambda t: -sum(per[t]))


def summary(names):
    L = ["# Test-time concentration in B1's projects", "",
         "Test time = each test's own duration in the plain run at the parent (saved by every B1 pair), summed over "
         "the project's ok pairs; share = the tests' summed time / all tests' summed time (not wall time). "
         "Generated by research/v2/b1_time_concentration.py.", "",
         "| Project | ok pairs | tests | median suite test time per pair (s) | slowest test | top-1 share | "
         "top-10 share | top-1% of tests share |", "|---|---|---|---|---|---|---|---|"]
    for name in names:
        b1.use(name)
        per, total, n = durations(name)
        if not n:
            L.append(f"| {name} | 0 | | | | | | |")
            continue
        rk = ranked(per)
        share = lambda ts: 100 * sum(sum(per[t]) for t in ts) / total
        k1 = max(1, len(rk) // 100)
        suite = statistics.median(sum(v) for v in _per_pair(name))
        L.append(f"| {name} | {n} | {len(rk)} | {suite:.0f} | `{rk[0]}` | {share(rk[:1]):.1f}% | "
                 f"{share(rk[:10]):.1f}% | {share(rk[:k1]):.1f}% ({k1} tests) |")
    out = os.path.join(b1.OUT, "time_concentration.md")
    open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


def _per_pair(name):
    for r in ok_rows(name):
        base = PL.jload(os.path.join(PL.BASE_WORK, name, "b1", r["id"][:12], "base_outcomes.json"))
        if base:
            yield [s for t, (_, s) in base.items() if "::" in t and s]


def pair_selections(r, keep):
    """{scenario: {tool: sorted selected tests among keep | {"error"}}, sizes: {scenario: {tool: [recomputed, row]}}}"""
    p, c = r["parent"], r["id"]
    d = os.path.join(PL.WORK, "b1", c[:12])
    cov, base = PL.jload(os.path.join(d, "covmap.json")), PL.jload(os.path.join(d, "base_outcomes.json"))
    if not cov or not base or (cov.get("__base__") or {}).get("commit") != p:
        return {"error": "no usable saved map/base outcomes at P"}
    universe = PL.universe_of(cov, PL.failing(base))
    tree = PL.make_tree("tc-main", p)
    b1.use_targets(tree)
    if PL.CFG.get("sync"):
        PL.CFG["sync"](tree, PL.PY)
    out, sizes = {}, {}
    with tempfile.TemporaryDirectory() as tmp:
        assets = {}
        if os.path.exists(os.path.join(d, "testmondata")):
            assets["testmon"] = shutil.copy(os.path.join(d, "testmondata"), os.path.join(tmp, "testmondata"))
        else:
            assets["testmon_error"] = "no saved testmon database"
        if os.path.isdir(os.path.join(d, "nr-cache")):
            assets["nr_cache"] = shutil.copytree(os.path.join(d, "nr-cache"), os.path.join(tmp, "nr-cache"))
            assets["nr_tree"] = PL.make_tree("tc-nr", p)
        else:
            assets["nr_error"] = "no saved NameRTS cache"
        for sc in ("S", "F"):
            if sc not in r or r[sc].get("timeout"):
                continue
            b1.to_parent(tree, p)
            if sc == "S":
                changed = b1.apply_source(tree, p, c)
                apply_to, edited = (lambda t: b1.apply_source(t, p, c)), []
            else:
                b1.apply_full(tree, p, c)
                changed = [f for _, f in b1._changed(tree, p, c)]
                apply_to = lambda t: b1.apply_full(t, p, c)
                edited = [f for f in changed if I._is_test_path(f) and f.endswith(".py")]
            ch = b1.SEL.Change(tree, [PL.CFG["pkg"]])
            sets, _ = b1.selections(tree, cov, universe, assets, p, apply_to, ch.files or changed)
            ed = {n for n in universe if n.split("::", 1)[0] in set(edited)}
            out[sc], sizes[sc] = {}, {}
            for tool, _ in TOOLS:
                s = sets.get(tool)
                row_n = ((r[sc].get("tools") or {}).get(tool) or {}).get("selected")
                if s is None or isinstance(s, dict):
                    out[sc][tool] = {"error": (s or {}).get("error", "not run")}
                    sizes[sc][tool] = [None, row_n]
                    continue
                s = s | ed
                out[sc][tool] = sorted(s & keep)
                sizes[sc][tool] = [len(s), row_n]
        b1.to_parent(tree, p)
    return {"sel": out, "sizes": sizes}


def detail(name, top, max_load):
    b1.use(name)
    per, total, n = durations(name)
    rk = ranked(per)[:top]
    keep = set(rk)
    cache = os.path.join(PL.WORK, "time_concentration")
    os.makedirs(cache, exist_ok=True)
    rows = ok_rows(name)
    res = {}
    for k, r in enumerate(rows):
        f = os.path.join(cache, f"{r['id'][:12]}.json")
        got = PL.jload(f)
        if got is None or not keep <= set(got.get("keep", [])):
            while os.getloadavg()[0] > max_load:
                time.sleep(60)
            t = time.time()
            try:
                got = pair_selections(r, keep)
            except Exception as e:  # noqa: BLE001
                got = {"error": repr(e)[:300]}
            got["keep"] = sorted(keep)
            PL.jdump(got, f)
            print(time.strftime("%H:%M:%S"), f"[{k + 1}/{len(rows)}] {r['id'][:10]}",
                  got.get("error") or got["sizes"], f"({time.time() - t:.0f} s)", flush=True)
        res[r["id"]] = got
    write_detail(name, per, total, n, rk, rows, res)


def write_detail(name, per, total, n, rk, rows, res):
    good = {i: g for i, g in res.items() if "sel" in g}
    L = [f"# {name}: test-time concentration and selection of the slowest tests", "",
         f"{n} ok B1 pairs; {len(per)} tests; summed test time over the pairs {total:.0f} s (each test's own duration "
         "in the plain run at the parent; not wall time). Share = the test's summed time / all tests' summed time. "
         "Selected: in how many pairs each tool's selection contained the test, scenario S (the commit's source "
         "changes, the parent's tests) and F (the whole commit; tests of edited test files count as selected for "
         "every tool, as in B1's scoring). Selections recomputed from each pair's saved data, without running tests "
         "(research/v2/b1_time_concentration.py).", "",
         "| # | Test | median s per run | share of test time | cumulative | ValueRTS S | ValueRTS F | testmon S | "
         "testmon F | NameRTS S | NameRTS F |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    cum = 0.0
    for k, t in enumerate(rk, 1):
        sh = 100 * sum(per[t]) / total
        cum += sh
        cells = []
        for tool, _ in TOOLS:
            for sc in ("S", "F"):
                have = [g["sel"][sc][tool] for g in good.values() if sc in g["sel"] and isinstance(g["sel"][sc].get(tool), list)]
                cells.append(f"{sum(t in s for s in have)}/{len(have)}")
        L.append(f"| {k} | `{t}` | {statistics.median(per[t]):.2f} | {sh:.1f}% | {cum:.1f}% | " + " | ".join(cells) + " |")
    L += ["", "Denominator = pairs where the tool produced a selection in that scenario (a tool error on a pair, or a "
          "scenario a pair lacks, is left out)."]
    # check: recomputed selection sizes against the sizes the rows recorded
    L += ["", "Check, recomputed selection size = size recorded in the B1 row:", ""]
    for tool, label in TOOLS:
        for sc in ("S", "F"):
            pairs = [g["sizes"][sc][tool] for g in good.values() if sc in g.get("sizes", {})]
            both = [x for x in pairs if x[0] is not None and x[1] is not None]
            L.append(f"- {label} {sc}: {sum(a == b for a, b in both)}/{len(both)} pairs equal"
                     + (f"; differing: {[(a, b) for a, b in both if a != b][:5]}" if any(a != b for a, b in both) else ""))
    errs = {i[:10]: g["error"] for i, g in res.items() if "error" in g}
    if errs:
        L += ["", f"Pairs without a recomputed selection: {errs}"]
    out = os.path.join(b1.res(), "time_concentration.md")
    open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


def main():
    a = sys.argv[1:]
    if a and a[0] == "summary":
        return summary(a[1:])
    if a and a[0] == "detail":
        top = int(a[a.index("--top") + 1]) if "--top" in a else 15
        ml = float(a[a.index("--max-load") + 1]) if "--max-load" in a else 9.0
        return detail(a[1], top, ml)
    sys.exit(__doc__)


if __name__ == "__main__":
    main()
